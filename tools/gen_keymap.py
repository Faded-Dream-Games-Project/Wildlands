#!/usr/bin/env python3
"""Dev-time tool (NOT part of the game): parse raylib.h's KeyboardKey enum and
emit src/core/key_names.inc, a { keycode, name } table used for rebindable
controls. Run from anywhere; output path is relative to the repo root."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAYLIB_H = ROOT / "third_party" / "raylib" / "src" / "raylib.h"
OUT = ROOT / "src" / "core" / "key_names.inc"


def pretty(name: str) -> str:
    # KEY_LEFT_SHIFT -> "LEFT SHIFT"
    return name.replace("_", " ")


def main() -> int:
    text = RAYLIB_H.read_text(encoding="utf-8")
    m = re.search(r"typedef enum\s*\{(.*?)\}\s*KeyboardKey;", text, re.S)
    if not m:
        print("KeyboardKey enum not found in raylib.h", file=sys.stderr)
        return 1

    entries = []
    value = 0
    for raw_line in m.group(1).splitlines():
        line = raw_line.split("//")[0].strip().rstrip(",").strip()
        if not line or not line.startswith("KEY_"):
            continue
        if "=" in line:
            name, val = line.split("=", 1)
            name = name.strip()
            try:
                value = int(val.strip(), 0)
            except ValueError:
                continue
        else:
            name = line
        entries.append((name, value))
        value += 1

    if len(entries) < 100:  # sanity: raylib has ~110 key codes
        print(f"only {len(entries)} keys parsed; aborting", file=sys.stderr)
        return 1

    with OUT.open("w", encoding="utf-8") as f:
        f.write("/* GENERATED by tools/gen_keymap.py from raylib.h — do not edit.\n")
        f.write(" * Included inside keybinds.c after raylib.h. */\n")
        f.write("static const WlKeyName wl_key_name_table[] = {\n")
        for name, value in entries:
            f.write(f"    {{ {name}, \"{pretty(name[4:])}\" }},\n")
        f.write("};\n")

    print(f"wrote {OUT} with {len(entries)} keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
